-- 계정·회차·신청 기본 스키마. 시각은 모두 timestamptz(UTC 저장).

create table account (
    id            bigint generated by default as identity primary key,
    login_id      varchar(50)  not null unique,
    password_hash varchar(100) not null,
    display_name  varchar(50)  not null,
    role          varchar(20)  not null check (role in ('OPERATOR', 'PARTICIPANT')),
    created_at    timestamptz  not null default now()
);

create table study_session (
    id         bigint generated by default as identity primary key,
    title      varchar(100) not null,
    starts_at  timestamptz  not null,
    location   varchar(200) not null,
    capacity   integer      not null check (capacity > 0),
    created_at timestamptz  not null default now()
);

-- 대기(WAITING) 상태는 후속 마이그레이션에서 check 제약만 넓혀 추가한다.
-- 활성 신청 = CANCELLED 가 아닌 신청이므로 WAITING 도 자동으로 활성 유일성에 포함된다.
create table reservation (
    id               bigint generated by default as identity primary key,
    study_session_id bigint      not null references study_session (id),
    account_id       bigint      not null references account (id),
    status           varchar(20) not null check (status in ('CONFIRMED', 'CANCELLED')),
    created_at       timestamptz not null default now(),
    cancelled_at     timestamptz,
    constraint ck_reservation_cancelled_at
        check ((status = 'CANCELLED') = (cancelled_at is not null))
);

-- 회차·계정별 활성 신청은 한 건만
create unique index ux_reservation_active
    on reservation (study_session_id, account_id)
    where status <> 'CANCELLED';

-- 잔여석 계산(회차별 확정 수)과 후속 대기 순번 조회용
create index ix_reservation_session_status
    on reservation (study_session_id, status, created_at);

create index ix_reservation_account
    on reservation (account_id);
