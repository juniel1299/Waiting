-- 확장 7단계: 모임 사진첩. 사진 정보(club_photo)와 저장된 바이트(photo_object)를 나눈다:
-- 바이트는 저장소 인터페이스(PhotoStorage) 뒤에 있어, 지금은 이 DB(Neon)에 두고 나중에 Supabase Storage 등으로 바꿀 수 있다.
-- 저장본은 서버가 다시 만든 JPEG(긴 변 1600px, EXIF 없음)와 썸네일(400px)뿐이고 원본은 저장하지 않는다.
create table club_photo (
    id                  bigint generated by default as identity primary key,
    club_id             bigint      not null references club (id) on delete cascade,
    uploader_account_id bigint      not null references account (id) on delete cascade,
    width               integer     not null check (width > 0),
    height              integer     not null check (height > 0),
    stored_bytes        integer     not null check (stored_bytes > 0),
    created_at          timestamptz not null
);

create index ix_club_photo_club on club_photo (club_id, id desc);
create index ix_club_photo_uploader on club_photo (uploader_account_id, created_at desc);

create table photo_object (
    photo_id bigint     not null references club_photo (id) on delete cascade,
    kind     varchar(5) not null check (kind in ('IMAGE', 'THUMB')),
    data     bytea      not null,
    primary key (photo_id, kind)
);
