-- 확장 6단계: 모임 채팅. 화면은 cursor(seq) 이후의 변경(새 메시지·삭제)을 짧은 간격으로 이어 받는다(증분 폴링).
-- seq 는 넣을 때와 지울 때마다 새로 받는다. 같은 모임의 쓰기는 모임 단위 잠금으로 한 줄로 서므로, 커밋 순서 = seq 순서라
-- 어떤 seq 를 본 뒤에는 그보다 작은 seq 가 나중에 나타나지 않는다(이어 받기에 빠짐이 없다).
create sequence club_chat_seq;

create table club_chat_message (
    id                    bigint generated by default as identity primary key,
    club_id               bigint        not null references club (id) on delete cascade,
    author_account_id     bigint        not null references account (id) on delete cascade,
    body                  varchar(1000) check (body is null or length(btrim(body)) > 0),
    seq                   bigint        not null,
    created_at            timestamptz   not null,
    deleted_at            timestamptz,
    deleted_by_account_id bigint        references account (id) on delete set null,
    -- 지우면 내용은 비우고 표시만 남긴다
    check ((deleted_at is null) = (body is not null))
);

create index ix_chat_club_seq on club_chat_message (club_id, seq);
create index ix_chat_club_id on club_chat_message (club_id, id desc);
create index ix_chat_author_created on club_chat_message (author_account_id, created_at desc);
