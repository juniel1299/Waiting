-- 3단계: 운영자 계정 관리. 이용 정지 시각과 운영 조치 기록.
-- 정지: 행·신청은 그대로 두고 로그인과 기존 세션만 막는다 (해제하면 그대로 이어서 쓴다).
alter table account add column suspended_at timestamptz;

-- 운영 조치 기록: 처리자·대상(계정 id 만)·조치·사유·시각·처리 건수.
-- 대상의 아이디·이름은 복사하지 않는다: 탈퇴하면 계정 행이 익명화되므로 기록에도 개인정보가 남지 않는다.
-- 계정 행은 지우지 않으므로(탈퇴는 익명화) FK 가 계정 삭제를 막는 일은 없다. 데모 계정은 조치 대상이 아니다.
create table moderation_action (
    id                     bigint generated by default as identity primary key,
    operator_account_id    bigint       not null references account (id),
    target_account_id      bigint       not null references account (id),
    action                 varchar(20)  not null check (action in ('SUSPEND', 'UNSUSPEND', 'FORCE_WITHDRAW')),
    reason                 varchar(500) not null check (length(btrim(reason)) > 0),
    cancelled_reservations integer      not null default 0,
    deleted_sessions       integer      not null default 0,
    created_at             timestamptz  not null
);

create index ix_moderation_action_created on moderation_action (created_at desc, id desc);
create index ix_moderation_action_target on moderation_action (target_account_id);
