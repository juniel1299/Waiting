-- 커뮤니티 3단계: 사이트 알림함 (대기 승격, 멘션).

-- 알림 한 건. 대상(회차·글·댓글)이나 받는 계정이 지워지면 DB 가 같은 문장에서 함께 지운다.
-- event_key 는 같은 사건을 한 번만 알리게 한다 (재시도·반복 요청에도 중복 없음):
--   PROMOTED:{신청 id}, MENTION:post:{글 id}:{계정 id}, MENTION:comment:{댓글 id}:{계정 id}
-- 문구는 저장하지 않고 읽을 때 대상의 현재 제목·작성자 표시로 만든다.
create table notification (
    id                   bigint generated by default as identity primary key,
    recipient_account_id bigint       not null references account (id) on delete cascade,
    type                 varchar(20)  not null check (type in ('PROMOTED', 'MENTION')),
    actor_account_id     bigint       references account (id) on delete cascade,
    session_id           bigint       references study_session (id) on delete cascade,
    post_id              bigint       references board_post (id) on delete cascade,
    comment_id           bigint       references comment (id) on delete cascade,
    event_key            varchar(80)  not null unique,
    read_at              timestamptz,
    created_at           timestamptz  not null,
    check ((type = 'PROMOTED' and session_id is not null and post_id is null)
        or (type = 'MENTION' and post_id is not null and session_id is null))
);

create index ix_notification_recipient on notification (recipient_account_id, created_at desc, id desc);
create index ix_notification_unread on notification (recipient_account_id) where read_at is null;
