-- 확장 2단계: 닉네임 유일성·기존 회원 이관, 프로필(소개·관심 태그), 즐겨찾기.

-- 1) 기존 닉네임 정리: NFC 정규화, 앞뒤 공백 제거, 연속 공백 하나로 (앱이 저장 전에 하는 정규화와 같다)
update account set nickname = regexp_replace(btrim(normalize(nickname, NFC)), '\s+', ' ', 'g') where nickname is not null;
update account set nickname = null where nickname is not null and nickname = '';

-- 2) 대소문자만 다른 것까지 같은 닉네임이 여럿이면, 가장 먼저 만든 계정만 그대로 두고 나머지는 뒤에 계정 id 를 붙인다
update account a set nickname = left(a.nickname, 10) || a.id
where a.nickname is not null
  and exists (select 1 from account b where b.nickname is not null and lower(b.nickname) = lower(a.nickname) and b.id < a.id);

-- 3) 닉네임이 없는 일반 회원(탈퇴·데모 제외)에게 무작위 한글 닉네임: 형용사 + 명사 + 계정 id (id 로 유일)
update account set nickname =
    (array['다정한','씩씩한','느긋한','반짝이는','상냥한','부지런한','용감한','포근한','명랑한','차분한'])[1 + (id % 10)::int]
    || (array['다람쥐','고래','부엉이','수달','여우','펭귄','고양이','토끼','판다','참새'])[1 + ((id / 10) % 10)::int]
    || id
where nickname is null and deleted_at is null and demo_trial_id is null;

-- 4) 유일성: 대소문자를 무시한 닉네임이 하나뿐 (탈퇴하면 닉네임을 지우므로 이름이 다시 풀린다)
create unique index ux_account_nickname on account (lower(nickname)) where nickname is not null;

-- 5) 프로필: 공개 소개(300자)와 관심 태그(최대 5개). 공개 프로필은 닉네임·소개·태그만 내보낸다
alter table account add column bio varchar(300);
alter table account add column interest_tags varchar(20)[] not null default '{}' check (cardinality(interest_tags) <= 5);

-- 6) 즐겨찾기: 모임 또는 회차 하나를 가리킨다. 계정·대상별 한 행(유일), 대상·계정이 지워지면 함께 지워진다
create table favorite (
    id         bigint generated by default as identity primary key,
    account_id bigint      not null references account (id) on delete cascade,
    club_id    bigint      references club (id) on delete cascade,
    session_id bigint      references study_session (id) on delete cascade,
    created_at timestamptz not null,
    check ((club_id is null) <> (session_id is null)),
    unique (account_id, club_id),
    unique (account_id, session_id)
);

create index ix_favorite_account on favorite (account_id, created_at desc);
