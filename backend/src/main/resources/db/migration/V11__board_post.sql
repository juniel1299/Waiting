-- 커뮤니티 1단계: 회원 게시판(COMMUNITY)과 서비스 공지(NOTICE). 모임 게시판은 5단계에서 club_id 와 함께 넓힌다.
-- 본문은 사용자가 쓴 원문 텍스트 그대로 저장한다 (화면은 텍스트로만 그리고 HTML 로 해석하지 않는다).
-- 작성자는 탈퇴해도 계정 행이 익명화되어 남으므로 글도 남고 작성자 표시만 '탈퇴한 회원' 이 된다.
create table board_post (
    id                bigint generated by default as identity primary key,
    board             varchar(20)   not null check (board in ('COMMUNITY', 'NOTICE')),
    author_account_id bigint        not null references account (id),
    title             varchar(100)  not null check (length(btrim(title)) > 0),
    body              varchar(5000) not null check (length(btrim(body)) > 0),
    created_at        timestamptz   not null,
    updated_at        timestamptz
);

-- 게시판별 최신순 목록·쪽 (검색어가 없을 때 이 순서로 읽고 한 쪽만큼에서 멈춘다)
create index ix_board_post_board_created on board_post (board, created_at desc, id desc);
