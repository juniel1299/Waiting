-- 커뮤니티 2단계: 공개 닉네임, 댓글·한 단계 답글, 댓글 추천, 멘션.

-- 공개 닉네임 (로그인 아이디와 별개). 비어 있으면 화면에 '회원{id}' 로 보인다. 탈퇴하면 지운다.
alter table account add column nickname varchar(20);

-- 댓글과 답글. 글이 지워지면 댓글이, 부모 댓글이 지워지면 답글이 같은 문장에서 함께 지워진다.
create table comment (
    id                bigint generated by default as identity primary key,
    post_id           bigint        not null references board_post (id) on delete cascade,
    parent_id         bigint        references comment (id) on delete cascade,
    author_account_id bigint        not null references account (id),
    body              varchar(1000) not null check (length(btrim(body)) > 0),
    created_at        timestamptz   not null,
    updated_at        timestamptz
);

create index ix_comment_post on comment (post_id, created_at, id);
create index ix_comment_parent on comment (parent_id) where parent_id is not null;

-- 답글은 한 단계만: 부모는 같은 글의 '댓글'(부모가 없는 것)이어야 한다. 서비스 검증의 마지막 방어선.
create function check_comment_depth() returns trigger language plpgsql as $$
begin
    if new.parent_id is not null and not exists (
        select 1 from comment p where p.id = new.parent_id and p.parent_id is null and p.post_id = new.post_id
    ) then
        raise exception 'reply must target a top-level comment of the same post' using errcode = '23514';
    end if;
    return new;
end
$$;

create trigger trg_comment_depth before insert or update of parent_id, post_id on comment
    for each row execute function check_comment_depth();

-- 추천: 계정당 댓글별 한 번을 기본 키가 보장한다 (동시 요청에도 중복 없음).
create table comment_like (
    comment_id bigint      not null references comment (id) on delete cascade,
    account_id bigint      not null references account (id),
    created_at timestamptz not null,
    primary key (comment_id, account_id)
);

-- 멘션: 글 또는 댓글에서 계정 id 로 연결한다 (표시는 현재 닉네임). 원본이 지워지면 함께 지워진다.
create table mention (
    id         bigint generated by default as identity primary key,
    post_id    bigint      references board_post (id) on delete cascade,
    comment_id bigint      references comment (id) on delete cascade,
    account_id bigint      not null references account (id),
    created_at timestamptz not null,
    check ((post_id is null) <> (comment_id is null)),
    unique (post_id, account_id),
    unique (comment_id, account_id)
);

create index ix_mention_account on mention (account_id);
