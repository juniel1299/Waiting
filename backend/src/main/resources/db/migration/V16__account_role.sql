-- 확장 1단계: 서비스 역할을 여러 개 둘 수 있게 한다.
-- 운영자 여부는 기존 account.role(PARTICIPANT·OPERATOR)을 그대로 기준으로 쓴다(기존 규칙·테스트·운영 계정 유지, 이관 없음).
-- 운영자 외에 더해지는 역할(지금은 개발자)은 account_role 에 둔다. 한 계정이 운영자 + 개발자일 수 있다. 데모 계정은 역할 없음.
create table account_role (
    account_id bigint      not null references account (id) on delete cascade,
    role       varchar(20) not null check (role in ('DEVELOPER')),
    primary key (account_id, role)
);

-- 역할 부여·회수 기록. 처리자·대상은 계정 id 로만 남겨 탈퇴하면 '탈퇴한 회원' 으로 보인다.
create table account_role_change (
    id                bigint generated by default as identity primary key,
    target_account_id bigint       not null references account (id),
    role              varchar(20)  not null check (role in ('OPERATOR', 'DEVELOPER')),
    action            varchar(10)  not null check (action in ('GRANT', 'REVOKE')),
    reason            varchar(200) not null check (length(btrim(reason)) > 0),
    actor_account_id  bigint       not null references account (id),
    created_at        timestamptz  not null
);

create index ix_account_role_change_created on account_role_change (created_at desc, id desc);
