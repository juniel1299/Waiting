-- 확장 5단계: 카카오·네이버 계정 연결. 공급자 사용자 id 만 둔다(이메일·닉네임·액세스 토큰은 저장하지 않음).
-- 한 소셜 계정은 한 회원에만, 한 회원은 공급자마다 하나. 탈퇴는 계정 행을 익명화해 남기므로 연결 행은 탈퇴 처리에서 지운다.
create table social_account (
    id               bigint generated by default as identity primary key,
    account_id       bigint       not null references account (id) on delete cascade,
    provider         varchar(10)  not null check (provider in ('KAKAO', 'NAVER')),
    provider_user_id varchar(100) not null check (length(btrim(provider_user_id)) > 0),
    linked_at        timestamptz  not null,
    unique (provider, provider_user_id),
    unique (account_id, provider)
);
