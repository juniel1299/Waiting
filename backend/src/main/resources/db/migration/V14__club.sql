-- 커뮤니티 4단계: 모임 신청·승인·가입.

-- 모임(신청서 겸 승인된 모임). 상태: PENDING(승인 대기) → APPROVED·REJECTED(반려 사유) / CANCELLED(신청자 취소).
-- 반려·취소된 신청은 고치면 다시 PENDING. 승인된 모임의 수정은 재승인 없이 바로 반영.
-- version 은 운영자 승인·반려와 신청자 수정·취소의 경합을 가른다 (운영자가 본 version 과 다르면 409).
create table club (
    id                 bigint generated by default as identity primary key,
    name               varchar(60)   not null check (length(btrim(name)) > 0),
    intro              varchar(2000) not null check (length(btrim(intro)) > 0),
    place              varchar(200)  not null check (length(btrim(place)) > 0),
    mode               varchar(10)   not null check (mode in ('OFFLINE', 'ONLINE', 'MIXED')),
    status             varchar(10)   not null check (status in ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
    reject_reason      varchar(500),
    creator_account_id bigint        not null references account (id),
    version            bigint        not null default 0,
    created_at         timestamptz   not null,
    submitted_at       timestamptz   not null,
    decided_at         timestamptz,
    updated_at         timestamptz
);

create index ix_club_status_created on club (status, created_at desc, id desc);
create index ix_club_creator on club (creator_account_id);

-- 가입: 계정당 모임별 한 행을 기본 키가 보장한다 (동시 가입에도 중복 없음). 모임이 지워지면 함께 지워진다.
-- 승인될 때 생성자가 첫 모임 운영자(MANAGER)로 들어간다 (임명·회수는 5단계).
create table club_member (
    club_id    bigint      not null references club (id) on delete cascade,
    account_id bigint      not null references account (id),
    role       varchar(10) not null check (role in ('MEMBER', 'MANAGER')),
    joined_at  timestamptz not null,
    primary key (club_id, account_id)
);

create index ix_club_member_account on club_member (account_id);

-- 승인·반려 결과 알림 (3단계 알림함 재사용). 모임이 지워지면 알림도 지워진다.
alter table notification add column club_id bigint references club (id) on delete cascade;
alter table notification drop constraint notification_type_check;
alter table notification add constraint notification_type_check
    check (type in ('PROMOTED', 'MENTION', 'CLUB_APPROVED', 'CLUB_REJECTED'));
alter table notification drop constraint notification_check;
alter table notification add constraint notification_check
    check ((type = 'PROMOTED' and session_id is not null and post_id is null and club_id is null)
        or (type = 'MENTION' and post_id is not null and session_id is null and club_id is null)
        or (type in ('CLUB_APPROVED', 'CLUB_REJECTED') and club_id is not null and session_id is null and post_id is null));
