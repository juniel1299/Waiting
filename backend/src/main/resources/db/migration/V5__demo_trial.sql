-- 가입 없는 데모 체험. 체험 하나 = 방문자 계정 + 샘플 참가자 계정 + 체험 회차 + 샘플 예약.
-- 체험에 속한 행은 demo_trial_id 로 묶이고, 만료되면 DemoService.purgeExpired 가 통째로 지운다.
create table demo_trial (
    id                    bigint generated by default as identity primary key,
    created_at            timestamptz not null,
    expires_at            timestamptz not null,
    -- "샘플 참가자 취소" 가 취소할 지정 예약. 정리 때 예약보다 먼저 지우지 않도록 FK 는 두지 않는다
    sample_reservation_id bigint
);

create index ix_demo_trial_expires_at on demo_trial (expires_at);

alter table account add column demo_trial_id bigint references demo_trial (id);
alter table study_session add column demo_trial_id bigint references demo_trial (id);

create index ix_account_demo_trial on account (demo_trial_id) where demo_trial_id is not null;
create index ix_study_session_demo_trial on study_session (demo_trial_id) where demo_trial_id is not null;
