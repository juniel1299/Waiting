-- 확장 3단계: 개선사항 접수·관리와 에러 로그(자체 요약).

-- 개선사항: 회원이 접수하고 개발자가 상태를 바꾼다. 작성자 계정은 탈퇴해도 익명화만 되므로 글은 남는다.
create table feedback (
    id                bigint generated by default as identity primary key,
    author_account_id bigint        not null references account (id) on delete cascade,
    category          varchar(10)   not null check (category in ('BUG', 'IDEA', 'OTHER')),
    title             varchar(100)  not null check (length(btrim(title)) > 0),
    body              varchar(2000) not null check (length(btrim(body)) > 0),
    page_path         varchar(200),
    status            varchar(20)   not null check (status in ('RECEIVED', 'IN_PROGRESS', 'VERIFY_REQUESTED', 'DONE', 'ON_HOLD')),
    resolution        varchar(2000),
    pr_url            varchar(300)  check (pr_url is null or pr_url ~ '^https://github\.com/[^\s]+$'),
    version           bigint        not null default 0,
    created_at        timestamptz   not null,
    updated_at        timestamptz   not null
);

create index ix_feedback_author on feedback (author_account_id, created_at desc, id desc);
create index ix_feedback_status on feedback (status, updated_at desc, id desc);

-- 상태 변경 기록: 검증 요청·보류는 사유 필수
create table feedback_history (
    id               bigint generated by default as identity primary key,
    feedback_id      bigint       not null references feedback (id) on delete cascade,
    from_status      varchar(20)  not null,
    to_status        varchar(20)  not null,
    reason           varchar(300),
    actor_account_id bigint       not null references account (id),
    created_at       timestamptz  not null,
    check (to_status not in ('VERIFY_REQUESTED', 'ON_HOLD') or length(btrim(coalesce(reason, ''))) > 0)
);

create index ix_feedback_history on feedback_history (feedback_id, created_at desc, id desc);

-- 에러 로그: 같은 지문(출처·정리한 메시지·경로 틀)을 한 행으로 모아 횟수와 처음·마지막 시각만 둔다.
-- 본문·쿠키·토큰·비밀번호·이메일은 저장 전에 지운다(ErrorMasking). 마지막으로 본 지 30일이 지나면 지운다.
create table error_group (
    id              bigint generated by default as identity primary key,
    fingerprint     char(64)     not null unique,
    source          varchar(10)  not null check (source in ('FRONTEND', 'BACKEND')),
    message         varchar(300) not null,
    path            varchar(200) not null,
    release         varchar(40)  not null,
    last_trace_id   varchar(32)  not null,
    last_event_id   varchar(32),
    occurrences     bigint       not null,
    first_seen_at   timestamptz  not null,
    last_seen_at    timestamptz  not null,
    last_alerted_at timestamptz
);

create index ix_error_group_last_seen on error_group (last_seen_at desc, id desc);

-- 알림: 개선사항 상태 변경(작성자에게), 새 오류·1시간 넘게 지나 다시 난 오류(개발자에게)
alter table notification add column feedback_id bigint references feedback (id) on delete cascade;
alter table notification add column error_group_id bigint references error_group (id) on delete cascade;
alter table notification drop constraint notification_type_check;
alter table notification add constraint notification_type_check
    check (type in ('PROMOTED', 'MENTION', 'CLUB_APPROVED', 'CLUB_REJECTED', 'FEEDBACK_STATUS', 'ERROR_ALERT'));
alter table notification drop constraint notification_check;
alter table notification add constraint notification_check
    check ((type = 'PROMOTED' and session_id is not null and post_id is null and club_id is null)
        or (type = 'MENTION' and post_id is not null and session_id is null and club_id is null)
        or (type in ('CLUB_APPROVED', 'CLUB_REJECTED') and club_id is not null and session_id is null and post_id is null)
        or (type = 'FEEDBACK_STATUS' and feedback_id is not null and session_id is null and post_id is null and club_id is null)
        or (type = 'ERROR_ALERT' and error_group_id is not null and session_id is null and post_id is null and club_id is null));
